export function defaultLifecycleTasks(type: HrLifecycleType) {
  const source = type === 'ONBOARDING' ? ONBOARDING_TASKS : OFFBOARDING_TASKS;
  return source.map(([title, description], order) => ({
    title,
    description,
    order: order + 1,
  }));
}
